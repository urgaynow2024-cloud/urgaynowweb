export function getThemeDefinition(id: string): ThemeDefinition | undefined {
  return Object.prototype.hasOwnProperty.call(THEME_REGISTRY, id) ? THEME_REGISTRY[id] : undefined;
}

export function getAllThemes(): ThemeDefinition[] {
  return THEME_ORDER.map((id) => THEME_REGISTRY[id]).filter(Boolean);
}
